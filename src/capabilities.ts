import { chartContributors } from "./chartInspection";
import type { DataTable } from "./data";
import { flowchartStructure } from "./flowchartEdits";
import type { DiagramState } from "./panel";
import { errorMessage } from "./protocol";

type Capability = { available: true } | { available: false; reason: string };
const rowCapabilities = new WeakMap<
  DiagramState,
  { source: string; table: DataTable; result: Capability }
>();

export function diagramCapabilities(
  state: DiagramState,
  table?: DataTable,
): {
  editStructure: Capability;
  inspectRows: Capability;
  updateChart: Capability;
} {
  const unavailable = (reason: string): Capability => ({ available: false, reason });
  const available = { available: true } as const;
  let editStructure: Capability;
  if (state.language !== "mermaid") {
    editStructure = unavailable("Requires a Mermaid flowchart.");
  } else if (state.source === undefined || state.error) {
    editStructure = unavailable("Requires available source without a render error.");
  } else {
    try {
      flowchartStructure(state.source);
      editStructure = available;
    } catch (error) {
      editStructure = unavailable(errorMessage(error));
    }
  }
  const chart = !state.chart
    ? unavailable("Requires a chart generated by diagram_chart.")
    : !table
      ? unavailable("Chart data is not loaded; refresh or supply a data source.")
      : state.source === undefined
        ? unavailable("The generated source is unavailable.")
        : state.chartPresentation?.blocked
          ? unavailable("Manual source changes alter generated data or structure.")
          : available;
  let inspectRows = state.error
    ? unavailable("Fix the chart render error before inspecting items.")
    : chart;
  if (inspectRows.available && state.chart?.options && table && state.source !== undefined) {
    const cached = rowCapabilities.get(state);
    if (cached?.source === state.source && cached.table === table) {
      inspectRows = cached.result;
    } else {
      try {
        chartContributors(state.chart, table, state.source, []);
      } catch {
        inspectRows = unavailable("Custom chart options alter generated data or structure.");
      }
      rowCapabilities.set(state, { source: state.source, table, result: inspectRows });
    }
  }
  return { editStructure, inspectRows, updateChart: chart };
}
